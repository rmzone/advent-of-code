#[derive(Debug, PartialEq)]
struct Robot {
    position: IVec2,
    velocity: IVec2,
}

pub fn process(input: &str, width: i32, height: i32) -> Result<String> {
    let (_, mut robots) = process_input(input).expect("Should parse!");
    let map_size = IVec2::new(width, height);

    let mut i = 0;
    let last_step = loop {
        for robot in robots.iter_mut() {
            robot.position = (robot.position + robot.velocity).rem_euclid(map_size);
        }

        i += 1;
        if tree_test(&robots) {
            debug_grid(&robots, map_size);
            break i;
        }
    };

    Ok(last_step.to_string())
}

fn tree_test(robots: &[Robot]) -> bool {
    robots
        .iter()
        .map(|Robot { position, .. }| position)
        .all_unique()
}

#[allow(dead_code)]
fn debug_grid(robots: &[Robot], map_size: IVec2) {
    for y in 0..map_size.y {
        for x in 0..map_size.x {
            match robots
                .iter()
                .filter(|Robot { position, .. }| position.x == x && position.y == y)
                .count()
            {
                0 => {
                    print!(".");
                }
                n => {
                    print!("{}", n);
                }
            }
        }

        println!();
    }
}

